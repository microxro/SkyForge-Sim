def swizzles(letters_sets, n):
    names = []
    for letters in letters_sets:
        for k in (2, 3, 4):
            for t in itertools.product(letters[:n], repeat=k):
                names.append(("".join(t), k))
    return names

def vec_struct(n):
    comps = "x, y, z, w"[: 3 * n - 2]
    rgba = "r, g, b, a"[: 3 * n - 2]
    out = [f"template <class T> struct vec<T, {n}> : vbase<T, {n}> {{", "    union {",
           f"        struct {{ T {comps}; }};", f"        struct {{ T {rgba}; }};"]
    for name, k in swizzles(["xyzw", "rgba"], n):
        out.append(f"        sw<T, {k}> {name};")
    out += ["    };", f"    MSL_VEC_COMMON({n})", "};", ""]
    return "\n".join(out)

