// Original single-stroke instrument font on a 4×6 grid (y up, baseline at 0). Drawn as
// round-capped strokes so it scales cleanly on any display; no font files are bundled.
import Foundation

public enum StrokeFont {
    public static let glyphWidth = 4.0
    public static let advance = 5.6

    /// Punctuation that sits in a narrow cell, as on avionics displays.
    static let narrow: Set<Character> = [".", ",", ":"]
    public static func advance(for c: Character) -> Double { narrow.contains(c) ? 2.2 : advance }

    public static func width(of s: String) -> Double {
        guard let last = s.uppercased().last else { return 0 }
        let total = s.uppercased().reduce(0) { $0 + advance(for: $1) }
        return total - (advance(for: last) - (narrow.contains(last) ? 1.2 : glyphWidth))
    }

    public static func glyph(_ c: Character) -> [[Point2]] {
        guard let g = table[c] else { return [] }
        return g.map { $0.map { Point2($0.0, $0.1) } }
    }

