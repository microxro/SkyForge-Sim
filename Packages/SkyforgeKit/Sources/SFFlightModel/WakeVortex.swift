// Wake turbulence: the trailing vortex pair left by a heavy aircraft, modelled as two infinite
// straight vortices with a Lamb-Oseen core (2-D Biot-Savart). The pair is separated by pi*b/4 (elliptic
// loading), produces downwash between the vortices and upwash outside, and decays with age. Its velocity
// is added to the ambient wind, so a following aircraft feels it through the normal aerodynamics.
// Simplifications: no vortex descent, no ground interaction, and no along-track velocity.
import Foundation

public struct WakeVortexPair: Sendable, Equatable {
    /// Centre of the pair in NED (m). Vertical position is the aircraft's altitude when it passed.
    public var centerNED: SIMD3<Double>
    /// Direction of the flight path in the horizontal plane (rad, from north).
    public var headingRad: Double
    /// Circulation of each vortex at birth (m^2/s).
    public var circulation: Double
    /// Separation of the two vortices (m), pi*b/4 for elliptic loading.
    public var separation: Double
    /// Lamb core radius (m).
    public var coreRadius: Double
    /// Exponential decay time constant of the strength (s).
    public var decayTime: Double
    /// Age of the pair (s).
    public var age: Double

    public init(centerNED: SIMD3<Double>, headingRad: Double, circulation: Double, separation: Double,
                coreRadius: Double = 1.0, decayTime: Double = 90, age: Double = 0) {
        self.centerNED = centerNED; self.headingRad = headingRad
        self.circulation = circulation.isFinite ? circulation : 0
        self.separation = max(separation, 0.1)
        self.coreRadius = max(coreRadius, 0.05)
        self.decayTime = max(decayTime, 1)
        self.age = max(age, 0)
    }

    /// Pair generated by an aircraft in steady flight: L = W = rho V Gamma (pi b / 4).
    public static func generated(by aircraft: AircraftConfig, tas: Double, density: Double,
                                 centerNED: SIMD3<Double>, headingRad: Double, age: Double = 0) -> WakeVortexPair {
        let span = aircraft.wingSpan
        let v = max(tas, 1), rho = max(density, 1e-6)
        let circ = 4 * aircraft.mass * 9.806_65 / (Double.pi * rho * v * span)
        return WakeVortexPair(centerNED: centerNED, headingRad: headingRad, circulation: circ,
                              separation: Double.pi * span / 4, age: age)
    }

    /// Current strength factor after decay.
    public var strength: Double { circulation * exp(-age / decayTime) }

    /// Velocity induced by the pair at a NED point (m/s, NED). Negative z is upward motion.
    public func velocityNED(at p: SIMD3<Double>) -> SIMD3<Double> {
        let gamma = strength
        guard gamma != 0 else { return .zero }
        let q = p - centerNED
        let r = SIMD3(-sin(headingRad), cos(headingRad), 0.0)
        let y = q.x * r.x + q.y * r.y        // lateral offset from the flight path
        let z = q.z                          // NED down
        let half = separation / 2
        // Right vortex carries -gamma and left carries +gamma, so the flow between them is downwash.
        let vy = inducedLateral(y: y, z: z, y0: half, z0: 0, gamma: -gamma)
            + inducedLateral(y: y, z: z, y0: -half, z0: 0, gamma: gamma)
        let vz = inducedDown(y: y, z: z, y0: half, z0: 0, gamma: -gamma)
            + inducedDown(y: y, z: z, y0: -half, z0: 0, gamma: gamma)
        return r * vy + SIMD3(0, 0, vz)
    }

    private func core(_ r2: Double) -> Double { 1 - exp(-r2 / (coreRadius * coreRadius)) }

    private func inducedLateral(y: Double, z: Double, y0: Double, z0: Double, gamma: Double) -> Double {
        let dy = y - y0, dz = z - z0
        let r2 = max(dy * dy + dz * dz, 1e-9)
        return -gamma / (2 * Double.pi) * dz / r2 * core(r2)
    }

    private func inducedDown(y: Double, z: Double, y0: Double, z0: Double, gamma: Double) -> Double {
        let dy = y - y0, dz = z - z0
        let r2 = max(dy * dy + dz * dz, 1e-9)
        return gamma / (2 * Double.pi) * dy / r2 * core(r2)
    }
}
